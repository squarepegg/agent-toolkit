#!/usr/bin/env python3
"""Generate evals/STATUS.md: per skill, what is proven for free (CI) and what the laptop runs showed.

  python3 evals/status.py --write   regenerate evals/STATUS.md (after editing claims or adding ledger rows)
  python3 evals/status.py --check   CI: exit 1 if evals/STATUS.md is not what the claims + ledger say

The file is a pure function of evals/claims/*.json, the witness registry and evals/outcome/ledger/*.jsonl, so the
check catches a hand-edited verdict or a forgotten regeneration.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "outcome"))
import check_claims  # noqa: E402
import registry  # noqa: E402
import verdict as V  # noqa: E402

OUT = os.path.join(HERE, "STATUS.md")


def render():
    fails, table = check_claims.check()
    verdicts = {t: V.verdict_all(t) for t in registry.TASKS}
    lines = ["# Skill evidence status", "",
             "Generated by `python3 evals/status.py --write`; CI fails if it is stale. How to read it: `evals/README.md`.", "",
             "| skill | proven free in CI (witness + tool) | not provable (policy) | gaps | agent outcome (laptop) |",
             "|---|---|---|---|---|"]
    for d, counts, _ in table:
        tasks = [t for t, x in registry.TASKS.items() if x["skill"] == d]
        out = ", ".join(f"{t}: " + " / ".join(f"**{v['verdict']}**" + (f" ({V.model_name(v['model']).split(' ')[0].split('/')[-1]})" if v.get("model") and len(verdicts[t]) > 1 else "") for v in verdicts[t]) for t in tasks) or "no task (gap)"
        checkable = counts["witness"] + counts["tool"] + counts["gap"] + counts["model"]
        lines.append(f"| {d} | {counts['witness'] + counts['tool']}/{checkable} | {counts['policy']} | {counts['gap']} | {out} |")
    lines += ["", "## Agent outcome (laptop runs, recomputed from `evals/outcome/ledger/`)", "",
              "Cells are runs passed (`k/n`) or, for mutation-score tasks, mean mutants killed (`mean/max`).", "",
              "| task | verdict | none | skill | control | p vs none | p vs control | stale rows | cost | model |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for t, vs in verdicts.items():
        for v in vs:
            c = v["cell"]
            lines.append(f"| {t} | {v['verdict']} | {c['none']} | {c['skill']} | {c['control']} | {v.get('p_vs_none', '')} | "
                         f"{v.get('p_vs_control', '')} | {v['stale_rows']} | ${v['cost_usd']} | {V.model_name(v['model']) if v.get('model') else ''} |")
    lines += ["", "## Claims", ""]
    for d, _, _ in table:
        doc = json.load(open(os.path.join(HERE, "claims", f"{d}.json")))
        lines += [f"### {d}", "", "| claim | kind | evidence |", "|---|---|---|"]
        for c in doc["claims"]:
            ev = ", ".join(f"`{b}`" for b in c.get("by", [])) or c.get("why", "")
            q = c["quote"].replace("|", "\\|")
            lines.append(f"| {q} | {c['kind']} | {ev.replace('|', '/')} |")
        lines.append("")
    if fails:
        lines += ["## Claim check failures", ""] + [f"- {f}" for f in fails] + [""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv):
    text = render()
    if "--write" in argv:
        with open(OUT, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT)}")
        return 0
    if "--check" in argv:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != text:
            print("evals/STATUS.md is stale: run `python3 evals/status.py --write` and commit it", file=sys.stderr)
            return 1
        print("evals/STATUS.md is current")
        return 0
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
